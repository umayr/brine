const { test, expect } = require('@playwright/test');
const baseURL = process.env.BRINE_ATTENDED_FIXTURE_URL;
test.skip(!baseURL, 'Requires explicitly started Linux synthetic-attended fixture; no native qualification');

test('synthetic producer and real Linux history: authenticated preview, confirm, manual typed lookup', async ({page}) => {
  let previewPosts=0, applyPosts=0, lookupGets=0;
  page.on('request', request => {
    const p = new URL(request.url()).pathname;
    if (request.method()==='POST' && p.endsWith('/operations/preview')) previewPosts++;
    if (request.method()==='POST' && p==='/api/stacks/observability/up') applyPosts++;
    if (request.method()==='GET' && p.startsWith('/api/operations/')) lookupGets++;
  });
  const login = await page.goto(new URL('/login?next=%2Fstacks%2Fobservability',baseURL).href);
  expect(login.headers()['x-brine-fixture']).toBe('synthetic-attended-no-qualification');
  await page.getByLabel('Username').fill('admin');
  await page.getByLabel('Password').fill('fixture-only-not-a-secret');
  await page.getByRole('button',{name:'Sign in'}).click();
  await expect(page).toHaveURL(new URL('/stacks/observability',baseURL).href);
  await expect(page.locator('#action-output')).toHaveAttribute('data-attended','true');
  const preview = page.waitForResponse(r => r.url().endsWith('/api/stacks/observability/operations/preview') && r.request().method()==='POST');
  await page.evaluate(() => runAction('up','observability'));
  const previewResponse = await preview;
  expect(previewResponse.status()).toBe(200);
  const previewId = previewResponse.headers()['x-brine-request-id'];
  expect(previewId).toMatch(/^br_[a-f0-9]{32}$/);
  await expect(page.locator('#action-log')).toContainText('observability');
  await expect(page.locator('#action-log')).toContainText('planned-name');
  expect(previewPosts).toBe(1);expect(applyPosts).toBe(0);expect(lookupGets).toBe(0);
  await page.locator('#attended-confirm input').check();
  const applied = page.waitForResponse(r => r.url().endsWith('/api/stacks/observability/up') && r.request().method()==='POST');
  await page.getByRole('button',{name:'Confirm once'}).click();
  const response=await applied;expect(response.status()).toBe(200);
  const applyId=response.headers()['x-brine-request-id'];expect(applyId).toMatch(/^br_[a-f0-9]{32}$/);expect(applyId).not.toBe(previewId);
  await expect(page.locator('#action-log')).toContainText('not acknowledgement or proof of success');
  await expect(page.locator('#operation-request-id')).toHaveValue(applyId);
  expect(lookupGets).toBe(0);
  await page.getByRole('button',{name:'Look up status',exact:true}).click();
  await expect(page.locator('#operation-lookup')).toContainText('brine.operation/2');
  await expect(page.locator('#operation-lookup')).toContainText('unknown');
  await expect(page.locator('#operation-lookup')).toContainText(previewId);
  expect(previewPosts).toBe(1);expect(applyPosts).toBe(1);expect(lookupGets).toBe(1);
});
