// Package revealaudit provides a durable, fail-closed journal for remote reveals.
//
// Open requires an existing private directory owned by the effective user (mode
// 0700 or stricter). Its ancestors, mount, and all cooperating processes must be
// trusted not to replace paths, change permissions, or modify journal files.
// In particular, mode checks do not inspect ACLs: the operator must ensure that
// no ACL grants access to anyone else. The filesystem must implement reliable
// flock, O_APPEND, file and directory fsync, and durable close semantics; network
// filesystems and filesystems that do not honor these guarantees are unsuitable.
// No automatic repair or rotation is performed. Back up and reconcile a damaged
// or full journal manually, with all writers stopped. Admission reserves logical
// journal capacity for outcomes, not disk blocks or quota. ENOSPC, quota, and
// other I/O failures can still prevent an outcome: deny delivery and reconcile
// the pending or ambiguous state manually. Initialize is explicit;
// Open never treats missing state as a fresh journal. Loss of the entire root is
// indistinguishable from a new root without an external inventory or anchor.
// Head updates precede journal appends; an interrupted update may render the
// journal unavailable until manual reconciliation. Context bounds lock waiting,
// but cannot interrupt a blocked operating-system filesystem call.
//
// The API accepts identifiers only, not reveal contents, grants, nonces, error
// messages, or other arbitrary metadata. The caller must ensure identifiers are
// non-secret public IDs; syntactic validation cannot establish that property.
// An error after an append may mean that the record exists despite the error.
// Never deliver a reveal on any error. Inspect the journal for reconciliation;
// do not infer an outcome from an error or automatically retry it.
package revealaudit

import (
	"bytes"
	"context"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"strings"
	"time"

	"golang.org/x/sys/unix"
)

const maxBytes = 8 << 20
const maxID = 128

// Outcome deliberately carries no free-form details.
type Outcome string

const (
	Succeeded Outcome = "succeeded"
	Failed    Outcome = "failed"
)

// Intent identifies an attempted reveal. Correlation is generated by this package.
type Intent struct {
	Correlation string `json:"correlation"`
	AdminID     string `json:"admin_id"`
	TargetID    string `json:"target_id"`
	ContainerID string `json:"container_id"`
}
type record struct {
	Version     int     `json:"version"`
	Kind        string  `json:"kind"`
	Intent      *Intent `json:"intent,omitempty"`
	Correlation string  `json:"correlation,omitempty"`
	Outcome     Outcome `json:"outcome,omitempty"`
}

// Audit names an existing private root. It holds no open descriptors and may be
// shared between goroutines. Every operation independently locks and validates.
type Audit struct {
	root  string
	fault func(string) error
	limit int64 // test-only lower bound; production uses maxBytes
}

func (a *Audit) inject(stage string) error {
	if a.fault != nil {
		return a.fault(stage)
	}
	return nil
}

// Open validates previously initialized state; it never creates missing files.
func Open(ctx context.Context, root string) (*Audit, error) {
	a := &Audit{root: root}
	if err := a.transaction(ctx, func(*os.File, map[string]Intent, map[string]Outcome) error { return nil }); err != nil {
		return nil, err
	}
	return a, nil
}

// Initialize creates a new journal in an empty trusted root. Never retry an
// uncertain initialization automatically; inspect the root manually instead.
func Initialize(ctx context.Context, root string) (_ *Audit, err error) {
	if ctx == nil {
		return nil, errors.New("revealaudit: nil context")
	}
	if err = ctx.Err(); err != nil {
		return nil, err
	}
	fd, e := unix.Open(root, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC|unix.O_NOFOLLOW, 0)
	if e != nil {
		return nil, e
	}
	dir := os.NewFile(uintptr(fd), root)
	defer closeJoin(&err, dir)
	var st unix.Stat_t
	if e = unix.Fstat(fd, &st); e != nil {
		return nil, e
	}
	if e = private(st, true); e != nil {
		return nil, e
	}
	lock, e := openFileAt(fd, "lock", unix.O_RDWR|unix.O_CREAT|unix.O_EXCL)
	if e != nil {
		return nil, e
	}
	defer closeJoin(&err, lock)
	if e = lock.Sync(); e != nil {
		return nil, e
	}
	if e = dir.Sync(); e != nil {
		return nil, e
	}
	if e = lockContext(ctx, lock); e != nil {
		return nil, e
	}
	head, e := openFileAt(fd, "head", unix.O_RDWR|unix.O_CREAT|unix.O_EXCL)
	if e != nil {
		return nil, e
	}
	defer closeJoin(&err, head)
	empty := sha256.Sum256(nil)
	if _, e = head.Write([]byte(fmt.Sprintf("%016x %x\n", 0, empty))); e != nil {
		return nil, e
	}
	if e = head.Sync(); e != nil {
		return nil, e
	}
	if e = dir.Sync(); e != nil {
		return nil, e
	}
	journal, e := openFileAt(fd, "journal", unix.O_RDWR|unix.O_APPEND|unix.O_CREAT|unix.O_EXCL)
	if e != nil {
		return nil, e
	}
	defer closeJoin(&err, journal)
	if e = journal.Sync(); e != nil {
		return nil, e
	}
	if e = dir.Sync(); e != nil {
		return nil, e
	}
	if e = ctx.Err(); e != nil {
		return nil, e
	}
	return &Audit{root: root}, nil
}

func validID(s string) bool {
	if len(s) == 0 || len(s) > maxID {
		return false
	}
	for _, c := range s {
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-' || c == '_' || c == '.' || c == ':') {
			return false
		}
	}
	return true
}
func validCorrelation(s string) bool {
	if len(s) != 64 {
		return false
	}
	b, e := hex.DecodeString(s)
	return e == nil && len(b) == 32 && hex.EncodeToString(b) == s
}

// BeginRevealAudit durably records intent before any reveal is attempted.
func (a *Audit) BeginRevealAudit(ctx context.Context, adminID, targetID, containerID string) (Intent, error) {
	if !validID(adminID) || !validID(targetID) || !validID(containerID) {
		return Intent{}, errors.New("revealaudit: invalid identifier")
	}
	var b [32]byte
	if _, err := io.ReadFull(rand.Reader, b[:]); err != nil {
		return Intent{}, fmt.Errorf("revealaudit: random: %w", err)
	}
	in := Intent{hex.EncodeToString(b[:]), adminID, targetID, containerID}
	err := a.transaction(ctx, func(f *os.File, intents map[string]Intent, outcomes map[string]Outcome) error {
		if _, ok := intents[in.Correlation]; ok {
			return errors.New("revealaudit: correlation collision")
		}
		return a.appendRecord(f, record{Version: 1, Kind: "intent", Intent: &in}, len(intents)-len(outcomes)+1)
	})
	if err != nil {
		return Intent{}, err
	}
	return in, nil
}

// Finish durably records a terminal outcome. Success may be delivered only
// after Finish(correlation, Succeeded) returns nil. An intent may finish once.
func (a *Audit) Finish(ctx context.Context, correlation string, outcome Outcome) error {
	if !validCorrelation(correlation) || (outcome != Succeeded && outcome != Failed) {
		return errors.New("revealaudit: invalid outcome")
	}
	return a.transaction(ctx, func(f *os.File, intents map[string]Intent, outcomes map[string]Outcome) error {
		if _, ok := intents[correlation]; !ok {
			return errors.New("revealaudit: unknown intent")
		}
		if _, ok := outcomes[correlation]; ok {
			return errors.New("revealaudit: already finished")
		}
		return a.appendRecord(f, record{Version: 1, Kind: "outcome", Correlation: correlation, Outcome: outcome}, len(intents)-len(outcomes)-1)
	})
}

// Entry is a persisted intent and its terminal outcome, if any. An empty
// outcome means unknown/pending, not failure.
type Entry struct {
	Intent  Intent
	Outcome Outcome
}

// Entries returns all intents and their outcomes in journal order, for manual
// reconciliation after restart or an ambiguous error.
func (a *Audit) Entries(ctx context.Context) ([]Entry, error) {
	var result []Entry
	err := a.transaction(ctx, func(f *os.File, _ map[string]Intent, outcomes map[string]Outcome) error {
		records, err := readRecords(f)
		if err != nil {
			return err
		}
		for _, r := range records {
			if r.Kind == "intent" {
				result = append(result, Entry{Intent: *r.Intent, Outcome: outcomes[r.Intent.Correlation]})
			}
		}
		return nil
	})
	return result, err
}

// Pending returns unfinished intents for manual reconciliation, in journal order.
func (a *Audit) Pending(ctx context.Context) ([]Intent, error) {
	var result []Intent
	err := a.transaction(ctx, func(f *os.File, intents map[string]Intent, outcomes map[string]Outcome) error {
		// Re-read to retain journal order; the lock protects this snapshot.
		records, err := readRecords(f)
		if err != nil {
			return err
		}
		for _, r := range records {
			if r.Kind == "intent" {
				if _, ok := outcomes[r.Intent.Correlation]; !ok {
					result = append(result, *r.Intent)
				}
			}
		}
		return nil
	})
	return result, err
}

func (a *Audit) appendRecord(f *os.File, r record, pending int) error {
	b, err := json.Marshal(r)
	if err != nil {
		return err
	}
	b = append(b, '\n')
	st, err := f.Stat()
	if err != nil {
		return err
	}
	// 256 bytes exceeds the maximum canonical outcome record size.
	limit := int64(maxBytes)
	if a.limit > 0 && a.limit < limit {
		limit = a.limit
	}
	if st.Size()+int64(len(b))+int64(pending)*256 > limit {
		return errors.New("revealaudit: journal full")
	}
	if err = a.writeHead(f, b); err != nil {
		return err
	}
	if err = a.inject("write"); err != nil {
		return err
	}
	n, err := f.Write(b)
	if err != nil {
		return err
	}
	if n != len(b) {
		return io.ErrShortWrite
	}
	if err = a.inject("fsync"); err != nil {
		return err
	}
	return f.Sync()
}

// head records the expected full journal digest and length. It is synced before
// the append: an interruption between the two leaves a detectable mismatch.
func (a *Audit) writeHead(f *os.File, addition []byte) (err error) {
	fd, e := unix.Open(a.root, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC|unix.O_NOFOLLOW, 0)
	if e != nil {
		return e
	}
	dir := os.NewFile(uintptr(fd), a.root)
	defer closeJoin(&err, dir)
	h, e := openFileAt(fd, "head", unix.O_RDWR)
	if e != nil {
		return e
	}
	defer closeJoin(&err, h)
	if _, e = f.Seek(0, io.SeekStart); e != nil {
		return e
	}
	data, e := io.ReadAll(io.LimitReader(f, maxBytes+1))
	if e != nil {
		return e
	}
	if len(data) > maxBytes {
		return errors.New("revealaudit: oversized journal")
	}
	data = append(data, addition...)
	sum := sha256.Sum256(data)
	b := []byte(fmt.Sprintf("%016x %x\n", len(data), sum))
	if e = a.inject("head-write"); e != nil {
		return e
	}
	n, e := h.WriteAt(b, 0)
	if e != nil {
		return e
	}
	if n != len(b) {
		return io.ErrShortWrite
	}
	if e = a.inject("head-fsync"); e != nil {
		return e
	}
	return h.Sync()
}
func (a *Audit) checkHead(dir int, f *os.File) (err error) {
	h, e := openFileAt(dir, "head", unix.O_RDONLY)
	if e != nil {
		return e
	}
	defer closeJoin(&err, h)
	expected, e := io.ReadAll(io.LimitReader(h, 83))
	if e != nil {
		return e
	}
	if len(expected) != 82 {
		return errors.New("revealaudit: malformed head")
	}
	if _, e = f.Seek(0, io.SeekStart); e != nil {
		return e
	}
	data, e := io.ReadAll(io.LimitReader(f, maxBytes+1))
	if e != nil {
		return e
	}
	if len(data) > maxBytes {
		return errors.New("revealaudit: journal too large")
	}
	sum := sha256.Sum256(data)
	actual := []byte(fmt.Sprintf("%016x %x\n", len(data), sum))
	if !bytes.Equal(expected, actual) {
		return errors.New("revealaudit: head/journal mismatch; manual reconciliation required")
	}
	return nil
}

func readRecords(f *os.File) ([]record, error) {
	st, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if st.Size() > maxBytes {
		return nil, errors.New("revealaudit: journal too large")
	}
	if _, err = f.Seek(0, io.SeekStart); err != nil {
		return nil, err
	}
	b, err := io.ReadAll(io.LimitReader(f, maxBytes+1))
	if err != nil {
		return nil, err
	}
	if len(b) > maxBytes {
		return nil, errors.New("revealaudit: journal too large")
	}
	if len(b) > 0 && b[len(b)-1] != '\n' {
		return nil, errors.New("revealaudit: partial record")
	}
	var rs []record
	for _, line := range bytes.Split(bytes.TrimSuffix(b, []byte("\n")), []byte("\n")) {
		if len(b) == 0 {
			break
		}
		if len(line) > 1024 {
			return nil, errors.New("revealaudit: oversized record")
		}
		var r record
		if err := json.Unmarshal(line, &r); err != nil {
			return nil, fmt.Errorf("revealaudit: malformed record: %w", err)
		}
		canonical, err := json.Marshal(r)
		if err != nil || !bytes.Equal(canonical, line) {
			return nil, errors.New("revealaudit: noncanonical record")
		}
		rs = append(rs, r)
	}
	return rs, nil
}

func validate(rs []record) (map[string]Intent, map[string]Outcome, error) {
	ins := map[string]Intent{}
	outs := map[string]Outcome{}
	for _, r := range rs {
		if r.Version != 1 {
			return nil, nil, errors.New("revealaudit: invalid version")
		}
		switch r.Kind {
		case "intent":
			i := r.Intent
			if i == nil || r.Correlation != "" || r.Outcome != "" || !validCorrelation(i.Correlation) || !validID(i.AdminID) || !validID(i.TargetID) || !validID(i.ContainerID) {
				return nil, nil, errors.New("revealaudit: invalid intent")
			}
			if _, ok := ins[i.Correlation]; ok {
				return nil, nil, errors.New("revealaudit: duplicate intent")
			}
			ins[i.Correlation] = *i
		case "outcome":
			if r.Intent != nil || !validCorrelation(r.Correlation) || (r.Outcome != Succeeded && r.Outcome != Failed) {
				return nil, nil, errors.New("revealaudit: invalid outcome record")
			}
			if _, ok := ins[r.Correlation]; !ok {
				return nil, nil, errors.New("revealaudit: orphan outcome")
			}
			if _, ok := outs[r.Correlation]; ok {
				return nil, nil, errors.New("revealaudit: duplicate outcome")
			}
			outs[r.Correlation] = r.Outcome
		default:
			return nil, nil, errors.New("revealaudit: invalid record kind")
		}
	}
	return ins, outs, nil
}

// closeJoin preserves close errors even when an earlier operation failed.
func closeJoin(errp *error, f *os.File) { *errp = errors.Join(*errp, f.Close()) }
func private(st unix.Stat_t, dir bool) error {
	typ := uint32(unix.S_IFREG)
	if dir {
		typ = unix.S_IFDIR
	}
	if uint32(st.Mode)&unix.S_IFMT != typ || st.Mode&0077 != 0 || st.Uid != uint32(os.Geteuid()) {
		return errors.New("revealaudit: insecure owner, mode, or file type")
	}
	if !dir && st.Nlink != 1 {
		return errors.New("revealaudit: hard-linked file")
	}
	return nil
}
func openFileAt(dir int, name string, flags int) (*os.File, error) {
	fd, err := unix.Openat(dir, name, flags|unix.O_CLOEXEC|unix.O_NOFOLLOW, 0600)
	if err != nil {
		return nil, err
	}
	f := os.NewFile(uintptr(fd), name)
	var st unix.Stat_t
	if err = unix.Fstat(fd, &st); err == nil {
		err = private(st, false)
	}
	if err != nil {
		return nil, errors.Join(err, f.Close())
	}
	return f, nil
}
func lockContext(ctx context.Context, f *os.File) error {
	for {
		if err := ctx.Err(); err != nil {
			return err
		}
		err := unix.Flock(int(f.Fd()), unix.LOCK_EX|unix.LOCK_NB)
		if err == nil {
			return nil
		}
		if err != unix.EWOULDBLOCK && err != unix.EAGAIN && err != unix.EINTR {
			return err
		}
		t := time.NewTimer(10 * time.Millisecond)
		select {
		case <-ctx.Done():
			t.Stop()
			return ctx.Err()
		case <-t.C:
		}
	}
}
func (a *Audit) transaction(ctx context.Context, fn func(*os.File, map[string]Intent, map[string]Outcome) error) (err error) {
	if ctx == nil {
		return errors.New("revealaudit: nil context")
	}
	if err = ctx.Err(); err != nil {
		return err
	}
	if a == nil || strings.TrimSpace(a.root) == "" {
		return errors.New("revealaudit: missing root")
	}
	fd, e := unix.Open(a.root, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC|unix.O_NOFOLLOW, 0)
	if e != nil {
		return e
	}
	dir := os.NewFile(uintptr(fd), a.root)
	defer closeJoin(&err, dir)
	var st unix.Stat_t
	if e = unix.Fstat(fd, &st); e != nil {
		return e
	}
	if e = private(st, true); e != nil {
		return e
	}
	lock, e := openFileAt(fd, "lock", unix.O_RDWR)
	if e != nil {
		return e
	}
	defer closeJoin(&err, lock)
	if e = lockContext(ctx, lock); e != nil {
		return e
	}
	if e = ctx.Err(); e != nil {
		return e
	}
	// Closing the lock releases flock; do not unlock before all durability checks.
	f, e := openFileAt(fd, "journal", unix.O_RDWR|unix.O_APPEND)
	if e != nil {
		return e
	}
	defer func() { closeJoin(&err, f); err = errors.Join(err, a.inject("close")) }()
	// Persist the empty file and both newly created directory entries.
	if e = f.Sync(); e != nil {
		return e
	}
	if e = a.inject("dirsync"); e != nil {
		return e
	}
	if e = dir.Sync(); e != nil {
		return e
	}
	if e = a.checkHead(fd, f); e != nil {
		return e
	}
	rs, e := readRecords(f)
	if e != nil {
		return e
	}
	ins, outs, e := validate(rs)
	if e != nil {
		return e
	}
	if e = ctx.Err(); e != nil {
		return e
	}
	if e = fn(f, ins, outs); e != nil {
		return e
	}
	// Directory sync is part of every successful operation, including appends.
	if e = a.inject("dirsync-final"); e != nil {
		return e
	}
	if e = dir.Sync(); e != nil {
		return e
	}
	return ctx.Err()
}
