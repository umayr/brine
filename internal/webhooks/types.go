// Package webhooks owns durable event delivery, not lifecycle execution.
package webhooks

import (
	"context"
	"errors"
	"time"
)

var (
	ErrNotFound = errors.New("webhook record not found")
	ErrInvalid  = errors.New("invalid webhook configuration")
	ErrCapacity = errors.New("webhook capacity exhausted")
	ErrConflict = errors.New("webhook record changed")
)

type Resource struct {
	ID   string `json:"id,omitempty"`
	Name string `json:"name,omitempty"`
	Kind string `json:"kind,omitempty"`
}

// Event contains allowlisted metadata only. Never populate it with output,
// credentials, environment values, source contents or receiver response bodies.
type Event struct {
	ID              string    `json:"id"`
	SchemaVersion   int       `json:"schema_version"`
	Type            string    `json:"type"`
	OccurredAt      time.Time `json:"occurred_at"`
	OperationID     string    `json:"operation_id,omitempty"`
	Stack           Resource  `json:"stack"`
	Source          Resource  `json:"source"`
	Target          Resource  `json:"target"`
	Action          string    `json:"action,omitempty"`
	Outcome         string    `json:"outcome,omitempty"`
	Effects         string    `json:"effects,omitempty"`
	ChangesDetected *bool     `json:"changes_detected,omitempty"`
	Reason          string    `json:"reason,omitempty"`
}

type Endpoint struct {
	ID        string    `json:"id"`
	Name      string    `json:"name"`
	URL       string    `json:"url"`
	Events    []string  `json:"events"`
	Stacks    []string  `json:"stacks"` // Empty means all stacks including future ones.
	Enabled   bool      `json:"enabled"`
	Version   int64     `json:"version"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`
}

type Delivery struct {
	ID            string    `json:"id"`
	EndpointID    string    `json:"endpoint_id"`
	Event         Event     `json:"event"`
	Status        string    `json:"status"`
	Attempts      int       `json:"attempts"`
	HTTPStatus    int       `json:"http_status,omitempty"`
	ErrorCategory string    `json:"error_category,omitempty"`
	NextAttemptAt time.Time `json:"next_attempt_at,omitempty"`
	CreatedAt     time.Time `json:"created_at"`
	UpdatedAt     time.Time `json:"updated_at"`
}

type Attempt struct {
	Number        int       `json:"number"`
	At            time.Time `json:"at"`
	DurationMS    int64     `json:"duration_ms"`
	HTTPStatus    int       `json:"http_status,omitempty"`
	ErrorCategory string    `json:"error_category,omitempty"`
}

type Config struct {
	Directory         string
	EncryptionKey     []byte   // Exactly 32 externally provisioned bytes; never autogenerated.
	AllowPrivateCIDRs []string // Explicit operator egress allowlist, not browser-controlled.
	MaxPending        int
	Retention         time.Duration
}

// Publisher persists an idempotently identified event before returning success.
// Stable IDs are required for transition replay/reconciliation after a crash.
type Publisher interface {
	Publish(context.Context, Event) error
}

// Catalog is the complete proposed version-1 event vocabulary. Monitoring
// producers must distinguish unavailable observations from known empty state.
var Catalog = []string{
	"operation.accepted", "operation.started", "operation.completed", "operation.outcome_unknown", "operation.rejected",
	"stack.created", "stack.updated", "stack.deleted", "source.revision_created", "source.restored",
	"git.sync.started", "git.sync.completed", "git.sync.failed", "git.sync.outcome_unknown",
	"target.enrolled", "target.updated", "target.removed", "target.connectivity_changed", "target.capabilities_changed",
	"container.state_changed", "container.health_changed", "stack.health_changed", "webhook.test",
}
